func TestScopesCountEachAccountsOwnPeriod(t *testing.T) {
	week := &reading{
		froms: map[string]int64{"d": 100, "k": 200, "cx": 150},
		owner: map[string]string{"d": "claude", "k": "claude", "cx": "codex"},
	}
	lines := []core.LogEntry{
		{T: 150, Account: "d"}, {T: 150, Account: "k"}, // k's week has not begun at 150
		{T: 250, Account: "k"}, {T: 160, Account: "cx"}, {T: 90, Account: "d"},
		{T: 300, Provider: "claude", History: true}, {T: 300, Account: "chatgpt:x", Provider: "codex"},
	}
	count := func(r *reading, scope string) int {
		in, _, ok := r.covers(scope)
		if !ok {
			return -1
		}
		n := 0
		for _, e := range lines {
			if in(e) {
				n++
			}
		}
		return n
	}
	for scope, want := range map[string]int{"all": 3, "provider:claude": 2, "d": 1, "k": 1, "cx": 1, "provider:nope": -1, "nope": -1} {
		if got := count(week, scope); got != want {
			t.Errorf("week, scope %s counts %d, want %d", scope, got, want)
		}
	}
	// Over a range a provider also counts lines without a known account; one account does not.
	// A provider listed without an account of its own still answers for its tokens.
	ranged := &reading{from: 100, froms: map[string]int64{"d": 100, "k": 100, "cx": 100}, owner: week.owner,
		providers: []usageProvider{{Provider: "claude"}, {Provider: "codex"}, {Provider: "gemini"}}}
	for scope, want := range map[string]int{"all": 6, "provider:claude": 4, "provider:codex": 2, "d": 1, "provider:gemini": 0, "provider:nope": -1} {
		if got := count(ranged, scope); got != want {
			t.Errorf("range, scope %s counts %d, want %d", scope, got, want)
		}
	}
}

