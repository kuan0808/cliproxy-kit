// After a restart the proxy has read no quota yet, so its state knows no weekly window; the log
// does. Placing the week a week before now instead would take the last window's readings in and
// call the new window's first reading use outside the proxy.
func TestTheWeekComesFromTheLogUntilTheProxyReadsAgain(t *testing.T) {
	const day = 24 * time.Hour
	now := time.Date(2026, 10, 6, 3, 0, 0, 0, time.UTC)
	reset := time.Date(2026, 10, 11, 12, 0, 0, 0, time.UTC) // this window: 10/4 12:00 to 10/11 12:00
	used := func(f float64) *float64 { return &f }
	ms := func(tm time.Time) int64 { return tm.UnixMilli() }
	lines := []core.LogEntry{
		// The window before, nearly used up.
		{T: ms(reset.Add(-8 * day)), Account: "a", Provider: "claude", Poll: true, Used7d: used(0.9), Reset7: ms(reset.Add(-7 * day))},
		// This window: a reading at 0, then a session's request and the reading after it.
		{T: ms(reset.Add(-6 * day)), Account: "a", Provider: "claude", Poll: true, Used7d: used(0), Reset7: ms(reset)},
		{T: ms(reset.Add(-6*day + time.Hour)), Account: "a", Provider: "claude", Session: "s", Output: 1000},
		{T: ms(reset.Add(-6*day + 2*time.Hour)), Account: "a", Provider: "claude", Poll: true, Used7d: used(0.1), Reset7: ms(reset)},
	}
	attribute := func(info core.AccountInfo) core.Attribution {
		ws := weekStart(info, now).UnixMilli()
		return core.Attribute(lines, "a", core.Span{From: ws - core.WindowJitter, To: ms(now), CountFrom: ws - core.WindowJitter, LogStart: lines[0].T, WindowStart: ws})
	}
	info := windowOf(core.AccountInfo{ID: "a", Provider: "claude"}, lines, now)
	if !info.ResetAt.Equal(reset) {
		t.Fatalf("reset = %v, want %v", info.ResetAt, reset)
	}
	// The same parts as once the proxy has read the account itself.
	got, want := attribute(info), attribute(core.AccountInfo{ID: "a", Provider: "claude", ResetAt: reset})
	if !near(got.Used, 0.1) || !near(got.Sessions["s"].Used, want.Sessions["s"].Used) ||
		!near(got.Outside, want.Outside) || !near(got.BeforeLog, want.BeforeLog) {
		t.Fatalf("from the log %+v, read by the proxy %+v", got, want)
	}
	// What the proxy read itself stands; a window the log saw end rolls on by whole weeks.
	own := time.Date(2026, 10, 12, 0, 0, 0, 0, time.UTC)
	if got := windowOf(core.AccountInfo{ID: "a", ResetAt: own}, lines, now); !got.ResetAt.Equal(own) {
		t.Fatalf("own reset = %v", got.ResetAt)
	}
	if got := windowOf(core.AccountInfo{ID: "a"}, lines, reset.Add(8*day)); !got.ResetAt.Equal(reset.Add(14 * day)) {
		t.Fatalf("rolled reset = %v", got.ResetAt)
	}
}

